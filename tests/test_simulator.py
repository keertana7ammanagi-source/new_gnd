import unittest
import os
import time
from telemetry.telemetry_manager import TelemetryManager
from storage.csv_logger import CSVLogger
from simulation.telemetry_simulator import TelemetrySimulator
from config.settings import ExecutionMode, DATA_DIR, CSV_PREFIX, TEAM_ID
from config.telemetry_schema import EXPECTED_FIELD_COUNT

class TestSimulator(unittest.TestCase):
    def setUp(self):
        self.manager = TelemetryManager()
        self.logger = CSVLogger(mode=ExecutionMode.SIMULATION)
        self.simulator = TelemetrySimulator(self.manager, self.logger)

    def test_simulator_csv_separation(self):
        """Verify Simulator CSV filename is completely separate from REAL mode."""
        self.assertTrue(self.logger.filepath.startswith(os.path.join(DATA_DIR, f"Sim_{CSV_PREFIX}")))
        self.assertNotEqual(self.logger.filepath, os.path.join(DATA_DIR, f"{CSV_PREFIX}_{TEAM_ID}.csv"))

    def test_exact_37_field_output(self):
        """Verify the raw string generated by the simulator has exactly 37 fields."""
        raw_line = self.simulator._generate_raw_csv()
        parts = raw_line.split(",")
        self.assertEqual(len(parts), EXPECTED_FIELD_COUNT)

    def test_pipeline_integration(self):
        """Verify simulator feeds into the exact same manager pipeline without errors."""
        self.simulator._step_physics()
        raw_line = self.simulator._generate_raw_csv()
        self.simulator._process_raw_line(raw_line)
        
        # Check that it reached the manager
        latest = self.manager.get_latest()
        self.assertIsNotNone(latest)
        self.assertEqual(latest["TEAM_ID"], TEAM_ID)

    def test_progression(self):
        """Verify timestamp, packet count, state, and altitude progress realistically."""
        self.simulator.iteration = 13 # Right before ASCENT
        self.simulator._step_physics()
        self.assertEqual(self.simulator.states[self.simulator.state_index], "LAUNCH_PAD")
        
        self.simulator._step_physics() # Iteration 15 triggers ASCENT
        self.assertEqual(self.simulator.states[self.simulator.state_index], "ASCENT")
        
        prev_alt = self.simulator.altitude
        self.simulator._step_physics()
        self.assertGreater(self.simulator.altitude, prev_alt) # Altitude increases
        
        # Verify timestamp and packet count progressed
        self.assertEqual(self.simulator.packet_count, 3)
        self.assertGreater(self.simulator.mission_time, 0.0)

    def test_fault_injection_packet_loss(self):
        self.simulator.faults["packet_loss"] = True
        self.simulator._step_physics()
        self.simulator._process_raw_line(self.simulator._generate_raw_csv())
        # Iteration 1 loses a packet in our mock logic, let's step a few times
        for _ in range(15):
            self.simulator._step_physics()
            self.simulator._process_raw_line(self.simulator._generate_raw_csv())
            
        status = self.manager.get_status()
        self.assertGreater(status["total_lost"], 0)

    def test_fault_injection_duplicate(self):
        self.simulator.faults["duplicate"] = True
        self.simulator._step_physics()
        raw_line = self.simulator._generate_raw_csv()
        self.simulator._process_raw_line(raw_line)
        self.simulator._process_raw_line(raw_line) # duplicate injection mechanism
        
        status = self.manager.get_status()
        self.assertEqual(status["total_duplicates"], 1)

    def test_fault_injection_short_packet(self):
        self.simulator.faults["short_packet"] = True
        self.simulator._step_physics()
        raw_line = self.simulator._generate_raw_csv()
        self.assertEqual(len(raw_line.split(",")), 36)
        self.simulator._process_raw_line(raw_line)
        
        status = self.manager.get_status()
        self.assertEqual(status["total_invalid"], 1)

    def test_fault_injection_long_packet(self):
        self.simulator.faults["long_packet"] = True
        self.simulator._step_physics()
        raw_line = self.simulator._generate_raw_csv()
        self.assertEqual(len(raw_line.split(",")), 38)
        self.simulator._process_raw_line(raw_line)
        
        status = self.manager.get_status()
        self.assertEqual(status["total_invalid"], 1)

    def test_fault_injection_invalid_numeric(self):
        self.simulator.faults["invalid_numeric"] = True
        self.simulator._step_physics()
        raw_line = self.simulator._generate_raw_csv()
        self.simulator._process_raw_line(raw_line)
        
        self.assertTrue(any("Type conversion error" in w for w in self.manager.warnings))

    def test_fault_injection_time_backwards(self):
        self.simulator.faults["time_backwards"] = True
        self.simulator._step_physics()
        raw_line = self.simulator._generate_raw_csv()
        self.simulator._process_raw_line(raw_line)
        latest = self.manager.get_latest()
        self.assertLess(latest["TIMESTAMP"], 0)

    def test_fault_injection_count_anomaly(self):
        self.simulator.faults["count_jump"] = True
        self.simulator._step_physics()
        self.simulator._process_raw_line(self.simulator._generate_raw_csv())
        self.simulator._step_physics()
        self.simulator._process_raw_line(self.simulator._generate_raw_csv())
        
        status = self.manager.get_status()
        self.assertGreater(status["total_lost"], 0) # Jump detects as loss

if __name__ == '__main__':
    unittest.main()
